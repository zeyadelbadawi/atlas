/**
 * Frontend mirror of the backend audit event catalogue
 * (`atlas-backend/src/audit-log/catalog/audit-event-catalog.ts`): which
 * filter category every audited action belongs to, and which categories an
 * Academy owner can see at all.
 *
 * The backend already returns `category` on every entry; this mirror exists
 * for the FILTERS (the category select is built from it) and for the
 * coverage test that proves every action has an English and an Arabic
 * sentence. When an action is added to the backend catalogue, add it here
 * and give it copy in `auditLog.json` (both languages) — the test fails
 * until all three agree.
 */
