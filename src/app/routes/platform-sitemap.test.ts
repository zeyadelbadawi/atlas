/**
 * The platform host's sitemap and robots.txt have ONE source since B1
 * (DL-50): the marketing prerender (`src/marketing/prerender/seo-files.ts`,
 * run by `pnpm build`), generated from the page registry. Before B1 the
 * build's `vite-plugin-sitemap` wrote them from a hand-kept list
 * (`platform-sitemap.ts`, owner decision D6), and `public/robots.txt` was a
 * third copy. This pins that neither comes back, and that the generated
 * sitemap lists the indexable pages — the marketing pages, contact and the
 * legal documents, in both languages — and never the 404, a planned URL,
 * the blog or an app path.
 */
import { existsSync, readFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { describe, expect, it } from 'vitest';
import snapshot from '@/marketing/data/plans.snapshot.json';
import type { Plan } from '@/types/plan.types';
import { MARKETING_PAGES } from '@/marketing/registry';
import { buildMarketingSite } from '@/marketing/prerender/site';
import { MARKETING_PLANNED_PATHS } from '@/marketing/prerender/routing';

const ROOT = resolve(__dirname, '../../..');
const read = (file: string) => readFileSync(resolve(ROOT, file), 'utf8');

describe('platform sitemap and robots.txt: one source (B1)', () => {
  it('are no longer written by vite-plugin-sitemap or kept in public/', () => {
    expect(read('vite.config.ts')).not.toMatch(/from 'vite-plugin-sitemap'|Sitemap\(/);
    expect(existsSync(resolve(ROOT, 'public/robots.txt'))).toBe(false);
    expect(existsSync(resolve(ROOT, 'public/sitemap.xml'))).toBe(false);
  });

  it('are generated by the marketing prerender in `pnpm build`', () => {
    const scripts = JSON.parse(read('package.json')).scripts as Record<string, string>;
    expect(scripts.build).toContain('build:marketing');
    expect(scripts['build:marketing']).toContain('node scripts/marketing/prerender.mjs');
  });

  it('list the indexable pages of the registry and nothing else', () => {
    if (MARKETING_PAGES.length === 0) return;
    const site = buildMarketingSite({
      pages: MARKETING_PAGES,
      ctx: {
        plans: snapshot as unknown as Plan[],
        siteUrl: 'https://atlass.dpdns.org',
        buildDate: '2026-10-20',
      },
      assets: {
        stylesheets: [],
        moduleScripts: [],
        modulePreloads: [],
        themeScript: '/assets/t.js',
        fontPreloads: { en: [], ar: [] },
      },
    });
    const locs = site.files
      .filter((file) => file.path.startsWith('sitemaps/'))
      .flatMap((file) => [...file.contents.matchAll(/<loc>([^<]+)<\/loc>/g)].map((m) => m[1]))
      .map((url) => url.replace('https://atlass.dpdns.org', ''));
    for (const path of ['/', '/ar', '/pricing', '/ar/pricing', '/contact', '/privacy-policy', '/terms']) {
      expect(locs).toContain(path);
    }
    for (const path of ['/blog', '/404', '/index.html', '/dashboard', '/auth/register', ...MARKETING_PLANNED_PATHS]) {
      expect(locs).not.toContain(path);
    }
    expect(locs.some((loc) => loc.includes('404'))).toBe(false);
    const robots = site.files.find((file) => file.path === 'robots.txt')!.contents;
    expect(robots).toContain('Sitemap: https://atlass.dpdns.org/sitemap.xml');
  });
});
